// Package reset генерирует методы Reset() для структур, помеченных директивой
// // generate:reset.
//
// Пакет сканирует пакеты по заданным паттернам и для каждого найденного
// пакета записывает файл reset.gen.go с методами Reset().
//
// Сгенерированный метод Reset() возвращает поля структуры к начальным
// значениям:
//
//   - примитивы приводятся к нулевым значениям (0, "", false, ...);
//   - слайсы обрезаются по длине (остаются не nil);
//   - мапы очищаются встроенным clear;
//   - вложенные структуры со своим Reset() сбрасываются рекурсивно;
//   - не nil указатели сбрасывают значение по тем же правилам;
//   - поля интерфейсных типов проверяются через type assertion на
//     interface{ Reset() } и сбрасываются, если реализуют его.
package reset

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/token"
	"go/types"
	"log/slog"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"text/template"

	"golang.org/x/tools/go/packages"
)

// ResetDirective — текст директивы в комментарии над структурой,
// например: // generate:reset. Сброс структур с этой директивой
// генерируется в файл reset.gen.go.
const ResetDirective = "generate:reset"

// tmplSource — единый шаблон всего файла reset.gen.go. Отступы расставляет
// go/format.Source, поэтому в шаблоне они не нужны. Рекурсивный обход полей
// ничего не печатает: он собирает плоский список операций (op), который шаблон
// разворачивает через range/if. Указательная вложенность (if p != nil { ... })
// выражается парой операций kindGuard/kindEnd в этом же списке.
const tmplSource = `// Code generated by reset; DO NOT EDIT.

package {{.Package}}
{{range .Structs}}
func ({{.Recv}} *{{.Type}}) Reset() {
if {{.Recv}} == nil {
return
}

{{range .Ops}}{{if eq .Kind "assign"}}{{.Expr}} = {{.Zero}}
{{else if eq .Kind "slice"}}{{.Expr}} = {{.From}}[:0]
{{else if eq .Kind "map"}}clear({{.Expr}})
{{else if eq .Kind "assert"}}if resetter, ok := {{.Expr}}.(interface{ Reset() }); ok && {{.Expr}} != nil {
resetter.Reset()
}
{{else if eq .Kind "reset"}}{{.Expr}}.Reset()
{{else if eq .Kind "guard"}}if {{.Expr}} != nil {
{{else if eq .Kind "end"}}}
{{end}}{{end}}}
{{end}}`

var resetTmpl = template.Must(template.New("reset").Parse(tmplSource))

// Виды элементарных операций сброса в сгенерированном методе.
const (
	kindAssign = "assign" // v = zero
	kindSlice  = "slice"  // v = v[:0]
	kindMap    = "map"    // clear(v)
	kindAssert = "assert" // type assertion к interface{ Reset() } и вызов
	kindReset  = "reset"  // v.Reset()
	kindGuard  = "guard"  // if v != nil {
	kindEnd    = "end"    // }
)

// op — элементарная операция сброса одного поля.
type op struct {
	Kind string // одна из kind*-констант
	Expr string // выражение-приёмник: поле или разыменованный указатель
	From string // выражение-источник для kindSlice (у deref-слайса — в скобках)
	Zero string // литерал нулевого значения для kindAssign
}

// structData — данные для генерации одного метода Reset().
type structData struct {
	Recv string
	Type string
	Ops  []op
}

// fileData — данные для генерации всего файла reset.gen.go.
type fileData struct {
	Package string
	Structs []structData
}

// Run загружает пакеты по паттернам (по умолчанию "./...") относительно
// текущей директории, находит структуры с директивой // generate:reset и
// генерирует для каждого пакета reset.gen.go. Если logger равен nil,
// используется slog.Default().
//
// Аргументами могут быть паттерны ("./..."), пути к каталогам ("internal")
// и пути к .go-файлам ("internal/config/config.go").
func Run(logger *slog.Logger, patterns ...string) error {
	return newGenerator(logger).run("", patterns)
}

type generator struct {
	logger *slog.Logger
}

func newGenerator(logger *slog.Logger) *generator {
	if logger == nil {
		logger = slog.Default()
	}
	return &generator{logger: logger}
}

// run — основная логика генерации; dir задаёт рабочую директорию загрузки
// пакетов (пустая строка — текущая директория).
func (g *generator) run(dir string, patterns []string) error {
	patterns = normalizePatterns(dir, patterns)
	if len(patterns) == 0 {
		patterns = []string{"./..."}
	}
	g.logger.Info("scanning packages for // "+ResetDirective+" structs", "patterns", strings.Join(patterns, " "))

	// Сначала загружаем только синтаксис: полная проверка типов может завершиться
	// ошибкой, если исходники уже вызывают Reset(), а сгенерированного файла ещё
	// нет. На этом проходе строим overlay с временными объявлениями таких методов.
	syntaxPkgs, err := loadPackages(dir, patterns, syntaxLoadMode, nil)
	if err != nil {
		return err
	}
	if len(syntaxPkgs) == 0 {
		return fmt.Errorf("no packages loaded for patterns %s", strings.Join(patterns, " "))
	}
	overlay, err := buildResetOverlay(dir, syntaxPkgs)
	if err != nil {
		return err
	}

	pkgs, err := loadPackages(dir, patterns, typedLoadMode, overlay)
	if err != nil {
		return err
	}
	packages.PrintErrors(pkgs)

	// Если не загрузился ни один пакет (например, запуск вне Go-модуля), это
	// ошибка запуска, а не «помеченных структур нет» — сообщаем о ней.
	if len(pkgs) == 0 || allPackagesFailed(pkgs) {
		return fmt.Errorf("no packages loaded for patterns %s", strings.Join(patterns, " "))
	}
	g.logger.Debug("packages loaded", "count", len(pkgs))

	marked, byPkg := markStructs(pkgs)

	// Молчаливый прогон без результатов неотличим от «генератор не запустился»,
	// поэтому случай «помеченных структур нет» логируем отдельно.
	if len(byPkg) == 0 {
		g.logger.Warn("no structs marked with // " + ResetDirective + " found")
		return nil
	}
	g.logger.Debug("marked structs found", "count", len(marked), "packages", len(byPkg))

	for pkg, namedList := range byPkg {
		if err := g.generatePackage(pkg, namedList, marked); err != nil {
			return err
		}
	}
	return nil
}

// normalizePatterns приводит аргументы к паттернам, понятным go list.
// Путь к существующему каталогу без префикса дополняется "./": go list
// воспринимает каталог только в форме "./dir" ("sub" он считает именем
// пакета). Файлы (file.go), явные паттерны ("./...", "./dir") и имена
// пакетов ("fmt") остаются без изменений.
func normalizePatterns(dir string, patterns []string) []string {
	out := make([]string, 0, len(patterns))
	for _, p := range patterns {
		if p != "." &&
			!strings.HasPrefix(p, "./") && !strings.HasPrefix(p, "/") &&
			!strings.Contains(p, "...") &&
			isDir(filepath.Join(dir, p)) {
			p = "./" + p
		}
		out = append(out, p)
	}
	return out
}

// isDir сообщает, что путь существует и является каталогом.
func isDir(path string) bool {
	info, err := os.Stat(path)
	return err == nil && info.IsDir()
}

// Режимы загрузки пакетов для синтаксического и полного проходов.
const syntaxLoadMode = packages.NeedName | packages.NeedFiles | packages.NeedSyntax | packages.NeedDeps

const typedLoadMode = packages.NeedName |
	packages.NeedFiles |
	packages.NeedSyntax |
	packages.NeedTypes |
	packages.NeedTypesInfo |
	packages.NeedDeps

// loadPackages загружает пакеты с указанным уровнем информации. Overlay
// позволяет добавить временные объявления методов, не изменяя файлы на диске.
func loadPackages(dir string, patterns []string, mode packages.LoadMode, overlay map[string][]byte) ([]*packages.Package, error) {
	pkgs, err := packages.Load(&packages.Config{
		Dir:     dir,
		Mode:    mode,
		Overlay: overlay,
	}, patterns...)
	if err != nil {
		return nil, fmt.Errorf("load packages: %w", err)
	}
	return pkgs, nil
}

// buildResetOverlay добавляет временные методы Reset() в один из исходных
// файлов каждого пакета, если тип помечен директивой, но метод ещё не объявлен.
// go/packages использует этот overlay для проверки типов; на диске он не
// сохраняется и не попадает в результат генерации.
func buildResetOverlay(dir string, pkgs []*packages.Package) (map[string][]byte, error) {
	overlay := make(map[string][]byte)
	for _, pkg := range pkgs {
		if !isBasePackage(pkg) || len(pkg.Syntax) == 0 || len(pkg.GoFiles) == 0 {
			continue
		}

		marked := make([]*ast.TypeSpec, 0)
		existingMethods := make(map[string]bool)
		for _, file := range pkg.Syntax {
			for _, decl := range file.Decls {
				switch decl := decl.(type) {
				case *ast.GenDecl:
					if decl.Tok != token.TYPE {
						continue
					}
					for _, spec := range decl.Specs {
						ts, ok := spec.(*ast.TypeSpec)
						if !ok {
							continue
						}
						if _, isStruct := ts.Type.(*ast.StructType); isStruct &&
							(hasResetDirective(decl.Doc) || hasResetDirective(ts.Doc)) {
							marked = append(marked, ts)
						}
					}
				case *ast.FuncDecl:
					if decl.Name.Name == "Reset" && decl.Recv != nil && len(decl.Recv.List) > 0 {
						if name := receiverTypeName(decl.Recv.List[0].Type); name != "" {
							existingMethods[name] = true
						}
					}
				}
			}
		}

		var stubs strings.Builder
		for _, ts := range marked {
			if existingMethods[ts.Name.Name] {
				continue
			}
			receiverType := ts.Name.Name
			if ts.TypeParams != nil && len(ts.TypeParams.List) > 0 {
				params := make([]string, 0)
				for _, field := range ts.TypeParams.List {
					for _, name := range field.Names {
						params = append(params, name.Name)
					}
				}
				receiverType += "[" + strings.Join(params, ", ") + "]"
			}
			fmt.Fprintf(&stubs, "\nfunc (*%s) Reset() {}\n", receiverType)
		}
		if stubs.Len() == 0 {
			continue
		}

		sourcePath := pkg.GoFiles[0]
		if !filepath.IsAbs(sourcePath) {
			sourcePath = filepath.Join(dir, sourcePath)
		}
		sourcePath, err := filepath.Abs(sourcePath)
		if err != nil {
			return nil, fmt.Errorf("resolve source path for %s: %w", pkg.PkgPath, err)
		}
		source, err := os.ReadFile(sourcePath)
		if err != nil {
			return nil, fmt.Errorf("read source file %s for reset overlay: %w", sourcePath, err)
		}
		overlay[sourcePath] = append(append(append([]byte(nil), source...), '\n'), []byte(stubs.String())...)
	}
	return overlay, nil
}

// receiverTypeName возвращает имя базового типа ресивера, в том числе для
// указателей и generic-типов (например, *Box[T]).
func receiverTypeName(expr ast.Expr) string {
	switch expr := expr.(type) {
	case *ast.Ident:
		return expr.Name
	case *ast.StarExpr:
		return receiverTypeName(expr.X)
	case *ast.IndexExpr:
		return receiverTypeName(expr.X)
	case *ast.IndexListExpr:
		return receiverTypeName(expr.X)
	case *ast.ParenExpr:
		return receiverTypeName(expr.X)
	default:
		return ""
	}
}

// allPackagesFailed сообщает, что все загруженные пакеты содержат ошибки.
func allPackagesFailed(pkgs []*packages.Package) bool {
	for _, pkg := range pkgs {
		if len(pkg.Errors) == 0 {
			return false
		}
	}
	return len(pkgs) > 0
}

// markStructs находит все структуры, помеченные // generate:reset. Возвращает
// карту помеченных типов и группировку структур по пакету. Помеченные типы
// считаются «имеющими Reset()» уже на этапе генерации — даже если сам метод
// ещё не написан в исходниках (он появится в генерируемом файле).
func markStructs(pkgs []*packages.Package) (map[*types.TypeName]bool, map[*packages.Package][]*types.Named) {
	marked := make(map[*types.TypeName]bool)
	byPkg := make(map[*packages.Package][]*types.Named)

	for _, pkg := range pkgs {
		if len(pkg.Errors) > 0 || !isBasePackage(pkg) {
			continue
		}
		for _, file := range pkg.Syntax {
			ast.Inspect(file, func(n ast.Node) bool {
				decl, ok := n.(*ast.GenDecl)
				if !ok || decl.Tok != token.TYPE {
					return true
				}
				for _, spec := range decl.Specs {
					named, ok := markedStruct(pkg, decl, spec)
					if !ok {
						continue
					}
					marked[named.Obj()] = true
					byPkg[pkg] = append(byPkg[pkg], named)
				}
				return true
			})
		}
	}
	return marked, byPkg
}

// markedStruct проверяет, что spec — объявление структуры с директивой
// // generate:reset, и возвращает её тип.
func markedStruct(pkg *packages.Package, decl *ast.GenDecl, spec ast.Spec) (*types.Named, bool) {
	ts, ok := spec.(*ast.TypeSpec)
	if !ok {
		return nil, false
	}
	if _, isStruct := ts.Type.(*ast.StructType); !isStruct {
		return nil, false
	}
	if !hasResetDirective(decl.Doc) && !hasResetDirective(ts.Doc) {
		return nil, false
	}
	obj, ok := pkg.TypesInfo.Defs[ts.Name].(*types.TypeName)
	if !ok {
		return nil, false
	}
	named, ok := obj.Type().(*types.Named)
	if !ok {
		return nil, false
	}
	return named, true
}

// generatePackage генерирует reset.gen.go для одного пакета: сортирует помеченные
// структуры по имени, рендерит файл единым шаблоном и записывает его, если
// содержимое изменилось.
func (g *generator) generatePackage(pkg *packages.Package, namedList []*types.Named, marked map[*types.TypeName]bool) error {
	sort.Slice(namedList, func(i, j int) bool {
		return namedList[i].Obj().Name() < namedList[j].Obj().Name()
	})

	data := fileData{Package: pkg.Name}
	for _, named := range namedList {
		data.Structs = append(data.Structs, genStructData(named, marked))
	}

	src, err := render(data)
	if err != nil {
		return fmt.Errorf("render reset.gen.go for %s: %w", pkg.PkgPath, err)
	}

	dir, err := packageDir(pkg)
	if err != nil {
		return fmt.Errorf("locate package %s: %w", pkg.PkgPath, err)
	}
	out := filepath.Join(dir, "reset.gen.go")
	changed, err := writeIfChanged(out, src)
	if err != nil {
		return fmt.Errorf("write %s: %w", out, err)
	}
	if changed {
		g.logger.Info("generated reset.gen.go", "path", out, "structs", len(namedList))
	} else {
		g.logger.Debug("reset.gen.go is up to date", "path", out)
	}
	return nil
}

// render исполняет шаблон и форматирует результат через go/format.
func render(data fileData) ([]byte, error) {
	var buf bytes.Buffer
	if err := resetTmpl.Execute(&buf, data); err != nil {
		return nil, fmt.Errorf("execute template: %w", err)
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated code: %w\n%s", err, buf.String())
	}
	return src, nil
}

// genStructData строит данные для метода Reset() структуры named.
func genStructData(named *types.Named, marked map[*types.TypeName]bool) structData {
	name := named.Obj().Name()
	data := structData{
		Recv: receiverName(name),
		Type: receiverType(named),
	}
	st := named.Underlying().(*types.Struct)
	for f := range st.Fields() {
		data.Ops = append(data.Ops, fieldOps(data.Recv+"."+f.Name(), f.Type(), marked)...)
	}
	return data
}

// fieldOps возвращает список операций сброса для поля acc типа t.
func fieldOps(acc string, t types.Type, marked map[*types.TypeName]bool) []op {
	u := t.Underlying()

	// Указатель: сбрасываем только не nil указатели, разыменовывая значение.
	if p, ok := u.(*types.Pointer); ok {
		inner := derefOps(acc, p.Elem(), marked)
		if len(inner) == 0 {
			return nil
		}
		return append(append([]op{{Kind: kindGuard, Expr: acc}}, inner...), op{Kind: kindEnd})
	}

	return valueOps(acc, t, marked)
}

// derefOps возвращает операции сброса значения, на которое указывает не nil
// указатель acc (тип элемента elem). Для структуры вызывается метод на самом
// указателе, для примитивов/слайсов/мап — на разыменованном значении.
func derefOps(acc string, elem types.Type, marked map[*types.TypeName]bool) []op {
	if _, ok := elem.Underlying().(*types.Struct); ok && hasReset(elem, marked) {
		return []op{{Kind: kindReset, Expr: acc}}
	}
	return scalarOps("*"+acc, "(*"+acc+")", elem.Underlying())
}

// valueOps возвращает операции сброса значения поля acc типа t (не указателя).
func valueOps(acc string, t types.Type, marked map[*types.TypeName]bool) []op {
	if _, ok := t.Underlying().(*types.Struct); ok && hasReset(t, marked) {
		return []op{{Kind: kindReset, Expr: acc}}
	}
	return scalarOps(acc, acc, t.Underlying())
}

// scalarOps возвращает операции сброса примитива, слайса, мапы или интерфейса
// для выражения acc (тип u); from — выражение-источник для обрезания слайса и
// type assertion (у deref-выражения — в скобках, что требуется синтаксисом
// x.(T)). Возвращает nil, если тип обработать нельзя.
func scalarOps(acc, from string, u types.Type) []op {
	switch v := u.(type) {
	case *types.Basic:
		if zero, ok := basicZero(v); ok {
			return []op{{Kind: kindAssign, Expr: acc, Zero: zero}}
		}
	case *types.Slice:
		return []op{{Kind: kindSlice, Expr: acc, From: from}}
	case *types.Map:
		return []op{{Kind: kindMap, Expr: acc}}
	case *types.Interface:
		return []op{{Kind: kindAssert, Expr: from}}
	}
	return nil
}

// isBasePackage возвращает true только для «основного» пакета (не для
// test-вариантов, которые go/packages загружает отдельно и для которых нельзя
// сгенерировать второй файл reset.gen.go в той же директории).
func isBasePackage(pkg *packages.Package) bool {
	return pkg.ForTest == "" && !strings.Contains(pkg.ID, " [")
}

// hasResetDirective проверяет, содержит ли комментарий директиву generate:reset.
func hasResetDirective(doc *ast.CommentGroup) bool {
	if doc == nil {
		return false
	}
	for _, c := range doc.List {
		text := strings.TrimSpace(c.Text)
		text = strings.TrimPrefix(text, "//")
		text = strings.TrimPrefix(text, "/*")
		text = strings.TrimSuffix(text, "*/")
		if strings.TrimSpace(text) == ResetDirective {
			return true
		}
	}
	return false
}

// packageDir возвращает директорию, в которой лежат исходники пакета.
func packageDir(pkg *packages.Package) (string, error) {
	if len(pkg.GoFiles) == 0 {
		return "", fmt.Errorf("no Go files")
	}
	return filepath.Dir(pkg.GoFiles[0]), nil
}

// writeIfChanged записывает файл только если его содержимое изменилось,
// сохраняя права уже существующего файла (для нового используется 0o644).
// Возвращает true, если файл был перезаписан.
func writeIfChanged(path string, data []byte) (bool, error) {
	mode := os.FileMode(0o644)
	if info, err := os.Stat(path); err == nil {
		mode = info.Mode().Perm()
		if old, err := os.ReadFile(path); err == nil && bytes.Equal(old, data) {
			return false, nil
		}
	}
	if err := os.WriteFile(path, data, mode); err != nil {
		return false, err
	}
	return true, nil
}

// receiverName строит короткое имя ресивера из имени типа (первая буква в нижнем
// регистре, с запасным вариантом "r").
func receiverName(typeName string) string {
	if typeName == "" {
		return "r"
	}
	c := typeName[0]
	switch {
	case c >= 'A' && c <= 'Z':
		return string(c + ('a' - 'A'))
	case c >= 'a' && c <= 'z':
		return string(c)
	default:
		return "r"
	}
}

// receiverType возвращает имя типа для ресивера с учётом параметров типа.
func receiverType(named *types.Named) string {
	s := named.Obj().Name()
	if tp := named.TypeParams(); tp != nil && tp.Len() > 0 {
		names := make([]string, 0, tp.Len())
		for param := range tp.TypeParams() {
			names = append(names, param.Obj().Name())
		}
		s += "[" + strings.Join(names, ", ") + "]"
	}
	return s
}

// basicZero возвращает литерал нулевого значения для базового типа.
func basicZero(b *types.Basic) (string, bool) {
	switch {
	case b.Info()&types.IsBoolean != 0:
		return "false", true
	case b.Info()&types.IsString != 0:
		return `""`, true
	case b.Info()&(types.IsInteger|types.IsFloat|types.IsComplex) != 0:
		return "0", true
	case b.Kind() == types.UnsafePointer:
		return "nil", true
	}
	return "", false
}

// hasReset проверяет, есть ли у типа метод Reset() без параметров и результата
// (на значении или на указателе), либо помечен ли он директивой generate:reset.
func hasReset(t types.Type, marked map[*types.TypeName]bool) bool {
	if named, ok := t.(*types.Named); ok && marked[named.Obj()] {
		return true
	}
	for _, cand := range []types.Type{t, types.NewPointer(t)} {
		sel := types.NewMethodSet(cand).Lookup(nil, "Reset")
		if sel == nil {
			continue
		}
		fn, ok := sel.Obj().(*types.Func)
		if !ok {
			continue
		}
		sig, ok := fn.Type().(*types.Signature)
		if ok && sig.Params().Len() == 0 && sig.Results().Len() == 0 {
			return true
		}
	}
	return false
}
